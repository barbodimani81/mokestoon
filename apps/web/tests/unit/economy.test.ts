import assert from "node:assert/strict";
import test from "node:test";
import catalog from "../../../api/internal/economy/playtest.json" with {
  type: "json",
};
import {
  activities,
  requestTuning,
  routines,
} from "../../src/game/config/activities.ts";
import { characterIds } from "../../src/game/config/character-assets.ts";
import {
  emptyProgress,
  validProgress,
} from "../../src/persistence/progress.ts";

test("every request generated by the apartment meets its server catalog rules", () => {
  assert.equal(catalog.cooldown_ticks, requestTuning.cooldown);
  for (const friend of characterIds) {
    const pool = new Set(routines[friend].filter((a) => a !== "chat"));
    if (friend === "parsa") pool.add("jelly_eat");
    if (friend === "mahan") {
      pool.add("iqos");
      pool.add("cigarette");
    }
    assert.deepEqual(pool, new Set(catalog.character_requests[friend]));
    for (const activity of pool)
      assert.equal(
        activities[activity].ticks +
          (activity === "jelly_eat"
            ? requestTuning.jellyCoolingTicks +
              activities.jelly_prepare.ticks +
              activities.jelly_store.ticks
            : 0),
        Reflect.get(catalog.minimum_ticks, activity),
      );
  }
});
test("unsupported local economy records cannot enter the reward queue", () => {
  const empty = emptyProgress();
  assert.ok(validProgress(empty));
  assert.equal(validProgress({ ...empty, pending: [{ event: null }] }), false);
  assert.equal(validProgress({ ...empty, player: { faaz: 30 } }), false);
  assert.equal(
    validProgress({ ...empty, backup: { owner: "foreign", version: 0 } }),
    false,
  );
});
